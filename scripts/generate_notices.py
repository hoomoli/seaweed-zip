#!/usr/bin/env python3
"""Reproduce distribution notices from installed, locked runtime dependencies."""
import argparse
import hashlib
import json
import os
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]

# Reviewed upstream Apache-2.0 texts; reject version or license-byte drift.
APACHE_LICENSES = {
    ('github.com/coreos/go-oidc/v3', 'v3.16.0', 'NOTICE'): 'dccd26c6fd9c296daf44d0bc56bb4efc566edd4880381b3331c9a63e6e471338',
    ('github.com/coreos/go-oidc/v3', 'v3.16.0', 'LICENSE'): 'cb5e8e7e5f4a3988e1063c142c60dc2df75605f4c46515e776e3aca6df976e14',
    ('github.com/go-jose/go-jose/v4', 'v4.1.3', 'LICENSE'): 'cfc7749b96f63bd31c3c42b5c471bf756814053e847c10f3eb003417bc523d30',
}


def run(*args, env=None):
    return subprocess.check_output(args, cwd=ROOT, env={**os.environ, **(env or {})}).decode().strip()


def json_stream(text):
    decoder = json.JSONDecoder()
    while text.strip():
        obj, end = decoder.raw_decode(text.lstrip())
        yield obj
        text = text.lstrip()[end:]


def section(label, text):
    return '\n' + '=' * 78 + '\n' + label + '\n' + '=' * 78 + '\n' + text.strip() + '\n'


def runtime_modules():
    # Distribution targets, not the developer host, determine license coverage.
    modules = {}
    for arch in ('amd64', 'arm64'):
        for dep in json_stream(run('go', 'list', '-deps', '-json', './cmd/seaweed-zip', env={'GOOS':'linux','GOARCH':arch,'CGO_ENABLED':'0'})):
            module = dep.get('Module')
            if module and not module.get('Main'):
                if 'Replace' in module:
                    raise ValueError('Replacement modules require a separate provenance review')
                modules[module['Path']] = module
    return modules


def npm_license_files(name, package, directory):
    files = sorted(p for p in directory.iterdir() if p.is_file() and p.name.lower() in {'license', 'license.md', 'license.txt', 'licence', 'notice', 'notice.txt'})
    if files:
        return files
    fallbacks = {'@ant-design/icons-svg': ('4.6.0', 'ant-design-icons.txt'), 'toggle-selection': ('1.0.6', 'toggle-selection.txt'), 'is-mobile': ('5.0.0', 'is-mobile.txt')}
    if name not in fallbacks:
        raise ValueError(f'Missing npm license: {name}@{package["version"]}; review upstream before publishing')
    version, file = fallbacks[name]
    if version != package['version']:
        raise ValueError(f'License fallback version drift: {name}')
    return [ROOT / 'docs/licenses' / file]


def build_helper_notices():
    output = ''
    for name in ('vite', 'rollup', 'esbuild', 'rolldown', 'oxc-runtime'):
        directory = ROOT / 'web/node_modules' / name
        if not directory.is_dir() and name != 'vite':
            continue
        metadata = json.loads((directory / 'package.json').read_text())
        files = sorted(p for p in directory.iterdir() if p.is_file() and ('LICENSE' in p.name.upper() or p.name.upper().startswith(('NOTICE', 'COPYING'))))
        if not files:
            raise ValueError(f'Missing build helper license: {name}')
        for file in files:
            output += section(f'Build runtime helpers: {name}@{metadata["version"]} / {file.name}', file.read_text())
    return output


def generate():
    output = 'Third-party notices for the Seaweed Zip binary, UI and container.\nDependencies retain their original licenses. Generated by scripts/generate_notices.py.\n'
    goroot = pathlib.Path(run('go', 'env', 'GOROOT'))
    output += section('Go standard library and embedded timezone code (BSD-3-Clause)', (goroot / 'LICENSE').read_text())
    output += section('IANA timezone database', 'The embedded IANA timezone data is public domain.\nSource: https://www.iana.org/time-zones; embedded by the pinned Go toolchain.')
    modules = runtime_modules()
    for name, module in sorted(modules.items()):
        directory = pathlib.Path(module['Dir'])
        files = sorted(p for p in directory.iterdir() if p.is_file() and p.name != "LICENSE-LOGO" and (p.name.upper().startswith(('LICENSE', 'COPYING', 'NOTICE')) or p.name == 'SQLITE-LICENSE'))
        if not files:
            raise ValueError(f'Missing Go license: {name}')
        for file in files:
            text = file.read_text()
            reviewed_apache = APACHE_LICENSES.get((name, module['Version'], file.name)) == hashlib.sha256(file.read_bytes()).hexdigest()
            if not reviewed_apache and not any(grant in text.lower() for grant in ('permission is hereby granted', 'redistribution and use', 'public domain')):
                raise ValueError(f'Unreviewed license text: {name}/{file.name}')
            output += section(f'Go: {name}@{module["Version"]} / {file.name}', text)
    lock = json.loads((ROOT / 'web/package-lock.json').read_text())
    for path, package in sorted(lock['packages'].items()):
        if not path or package.get('dev'):
            continue
        if package.get('license') != 'MIT':
            raise ValueError(f'Unreviewed npm license: {path}')
        directory = ROOT / 'web' / path
        name = path.split('node_modules/')[-1]
        for file in npm_license_files(name, package, directory):
            output += section(f'npm: {name}@{package["version"]} / {file.name}', file.read_text())
    output += build_helper_notices()
    output += section('Mozilla CA root bundle (MPL-2.0)', 'The container copies the unmodified ca-certificates-bundle-20260909-r0 from\nthe digest-pinned Go Alpine builder; no Alpine executables are distributed.\nCorresponding source: https://gitlab.alpinelinux.org/alpine/ca-certificates/-/archive/20260909/ca-certificates-20260909.tar.bz2\nUpstream: https://hg.mozilla.org/projects/nss/file/tip/lib/ckfw/builtins/certdata.txt\nThe exact source archive above includes certdata.txt and its upstream notices. The Mozilla trust bundle is not licensed by this project MIT.\n\n' + (ROOT / 'docs/licenses/MPL-2.0.txt').read_text())
    return output


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generate()
    target = ROOT / 'THIRD_PARTY_NOTICES.txt'
    if args.check:
        if not target.is_file() or target.read_text() != text:
            sys.exit('Third-party notices drift; regenerate and review before publishing.')
        print('Third-party notices match the locked runtime dependency graph.')
    else:
        target.write_text(text)
        print('Generated THIRD_PARTY_NOTICES.txt')


if __name__ == '__main__':
    main()
